export function normalizeLocale(locale = "") {
  const value = locale.toLowerCase();
  if (value.startsWith("zh-tw") || value.startsWith("zh-hk") || value.startsWith("zh-hant")) return "zh-TW";
  if (value.startsWith("zh")) return "zh-CN";
  if (value.startsWith("ja")) return "ja";
  if (value.startsWith("en")) return "en";
  return "ko";
}

export function translate(locale, key, values = {}) {
  return (messages[locale]?.[key] || messages.ko[key] || key)
    .replace(/\{(\w+)\}/g, (_match, name) => values[name] ?? "");
}

export function applyStaticTranslations(root, locale) {
  root.documentElement.lang = locale;
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(locale, element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = translate(locale, element.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", translate(locale, element.dataset.i18nAria));
  });
}
